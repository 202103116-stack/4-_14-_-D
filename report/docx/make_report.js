// 코드 화면: report/screenshots/ 에서 이름이 base로 시작하는 캡처를 찾아 넣고, 없으면 점선 자리
function codeShot(base, label, widthMm = 165) {
  const dir = path.join(ROOT, 'report', 'screenshots');
  const hit = fs.existsSync(dir) && fs.readdirSync(dir).find((f) => f.startsWith(base) && /\.(png|jpe?g)$/i.test(f));
  if (hit) return img(path.join('report', 'screenshots', hit), widthMm);
  return S.figurePlaceholder(`(코드 화면 자리: ${label})`, 40, 150);
}

